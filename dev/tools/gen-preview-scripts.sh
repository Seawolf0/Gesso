#!/bin/sh
# Regenerates dev/preview/scripts.generated.js from manifest.json so the
# preview page loads exactly the same content scripts, in the same order.
set -e
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LIST="$(plutil -extract content_scripts.0.js json -o - "$ROOT/extension/manifest.json")"
printf '// Generated by dev/tools/gen-preview-scripts.sh — do not edit.\nwindow.__GESSO_SCRIPTS = %s;\n' "$LIST" > "$ROOT/dev/preview/scripts.generated.js"
